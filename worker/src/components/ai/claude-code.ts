import { z } from 'zod';
import {
  componentRegistry,
  ComponentRetryPolicy,
  runComponentWithRunner,
  defineComponent,
  inputs,
  outputs,
  parameters,
  port,
  param,
} from '@shipsec/component-sdk';
import { LLMProviderSchema, llmProviderContractName } from '@shipsec/contracts';
import { createIsolatedVolume } from '../../utils/isolated-volume';
import { requireOrgVirtualKey, shouldRouteViaLiteLLM, getSkillWorkspaceFiles } from './utils';

const inputSchema = inputs({
  task: port(
    z.string().min(1, 'Task cannot be empty').describe('The investigation task to perform.'),
    {
      label: 'Task',
      description:
        'The main objective for the Claude Code agent (e.g. "Investigate these alerts").',
    },
  ),
  context: port(
    z.unknown().optional().describe('Contextual data (JSON) to assist the investigation.'),
    {
      label: 'Context',
      description: 'Optional JSON data providing context (alerts, logs, previous findings).',
      connectionType: { kind: 'primitive', name: 'json' },
      allowAny: true,
      reason: 'Context is a dynamic JSON object.',
    },
  ),
  model: port(
    LLMProviderSchema()
      .default({
        provider: 'anthropic',
        modelId: 'claude-sonnet-4-20250514',
      })
      .describe('Model configuration for the agent.'),
    {
      label: 'Model',
      description: 'LLM provider configuration.',
      connectionType: { kind: 'contract', name: llmProviderContractName, credential: true },
    },
  ),
  tools: port(z.unknown().optional().describe('Anchor for tool-mode nodes.'), {
    label: 'Connected Tools',
    description: 'Connect tool-mode nodes here to expose them to the agent.',
    allowAny: true,
    reason: 'Tool-mode port acts as a graph anchor; payloads are not consumed directly.',
    connectionType: { kind: 'contract', name: 'mcp.tool' },
  }),
  supplementaryA: port(
    z
      .string()
      .optional()
      .describe('Additional data written to /workspace/supplementary-a.txt for the agent.'),
    {
      label: 'Supplementary Input A',
      description:
        'Optional text/data (e.g. scanner findings) written to a workspace file the agent can read.',
      allowAny: true,
      reason: 'Accepts any stringifiable data for the agent workspace.',
    },
  ),
  supplementaryB: port(
    z
      .string()
      .optional()
      .describe('Additional data written to /workspace/supplementary-b.txt for the agent.'),
    {
      label: 'Supplementary Input B',
      description:
        'Optional text/data (e.g. scanner findings) written to a workspace file the agent can read.',
      allowAny: true,
      reason: 'Accepts any stringifiable data for the agent workspace.',
    },
  ),
});

const parameterSchema = parameters({
  systemPrompt: param(
    z.string().default('').describe('Optional investigator prompt template override.'),
    {
      label: 'System Prompt',
      editor: 'textarea',
      rows: 5,
      description: 'Override the default investigator prompt template.',
    },
  ),
  autoApprove: param(z.boolean().default(true).describe('Automatically approve agent actions.'), {
    label: 'Auto Approve',
    editor: 'boolean',
    description: 'If true, the agent runs without user intervention.',
  }),
  providerConfig: param(
    z.record(z.string(), z.unknown()).default({}).describe('Additional Claude Code configuration.'),
    {
      label: 'Provider Config',
      editor: 'json',
      description: 'Additional configuration passed as environment variables.',
    },
  ),
  skills: param(
    z.array(z.string()).default([]).describe('Agent skill names to inject into the workspace.'),
    {
      label: 'Skills',
      editor: 'tags',
      description:
        'Select agent skills to inject into the workspace as .claude/skills/*/SKILL.md files.',
    },
  ),
});

const outputSchema = outputs({
  report: port(z.string(), {
    label: 'Report',
    description: 'The final markdown report generated by the agent.',
  }),
  rawOutput: port(z.string(), {
    label: 'Raw Output',
    description: 'Full stdout/stderr logs from the agent execution.',
  }),
});

const definition = defineComponent({
  id: 'core.ai.claude-code',
  label: 'Claude Code Agent',
  category: 'ai',
  runner: {
    kind: 'docker',
    image: 'ghcr.io/shipsecai/claude-code:latest',
    entrypoint: 'claude',
    network: 'host' as const,
    command: ['--help'],
  },
  inputs: inputSchema,
  outputs: outputSchema,
  parameters: parameterSchema,
  docs: 'Runs the Claude Code agent to perform autonomous investigations using connected tools.',
  retryPolicy: {
    maxAttempts: 1,
    initialIntervalSeconds: 2,
    maximumIntervalSeconds: 10,
    backoffCoefficient: 2,
    nonRetryableErrorTypes: ['ValidationError', 'ConfigurationError'],
  } satisfies ComponentRetryPolicy,
  ui: {
    slug: 'claude-code-agent',
    version: '1.0.0',
    type: 'process',
    category: 'ai',
    description: 'Autonomous coding and investigation agent powered by Claude.',
    icon: 'Bot',
    author: {
      name: 'ShipSecAI',
      type: 'shipsecai',
    },
  },
  async execute({ inputs, params }, context) {
    const { task, context: taskContext, model, supplementaryA, supplementaryB } = inputs;
    const { systemPrompt, skills: selectedSkills } = params;

    const { organizationId } = context.metadata;

    // 1. Read Hotplug session URL and token injected by the workflow orchestration
    const hotplugMcpUrl = context.metadata.hotplugMcpUrl;
    const hotplugMcpToken = context.metadata.hotplugMcpToken;

    // 2. Prepare MCP config for Claude Code
    // Claude Code accepts MCP config via --mcp-config flag pointing to a JSON file
    // Format: { "mcpServers": { "<name>": { "url": "...", "type": "sse" } } }
    const mcpConfig: Record<string, unknown> =
      hotplugMcpUrl && hotplugMcpToken
        ? {
            mcpServers: {
              'workflow-tools': {
                url: hotplugMcpUrl,
                headers: {
                  Authorization: `Bearer ${hotplugMcpToken}`,
                },
              },
            },
          }
        : { mcpServers: {} };

    // 3. Resolve LiteLLM virtual key if needed
    let orgVirtualKey: string | undefined;
    if (shouldRouteViaLiteLLM() && !model?.apiKey && organizationId) {
      orgVirtualKey = await requireOrgVirtualKey(organizationId, {
        consumer: 'Claude Code agent',
      });
    } else if (shouldRouteViaLiteLLM() && !model?.apiKey) {
      orgVirtualKey = await requireOrgVirtualKey(organizationId ?? null, {
        consumer: 'Claude Code agent',
      });
    }

    const providerEnv = buildProviderEnv(model, orgVirtualKey);

    // Add model flag env if a specific model is requested
    if (model?.modelId) {
      providerEnv.CLAUDE_CODE_MODEL = model.modelId;
    }

    // 4. Prepare Context and Prompt
    const contextJson = JSON.stringify(taskContext ?? {}, null, 2);

    const defaultPrompt = `
# Investigation Task
{{TASK}}

# Context
The following context is available in /workspace/context.json.
Please investigate the issue and generate a detailed report.
`;

    let finalPrompt: string;
    if (systemPrompt?.trim()) {
      finalPrompt = `${systemPrompt}\n\n# Task\n${task}`;
      if (taskContext && Object.keys(taskContext).length > 0) {
        finalPrompt +=
          '\n\n# Context\nThe following context is available in /workspace/context.json.';
      }
    } else {
      finalPrompt = defaultPrompt.replace('{{TASK}}', task);
    }

    // Append supplementary file references to the prompt
    const suppFiles: string[] = [];
    if (supplementaryA) suppFiles.push('/workspace/supplementary-a.txt');
    if (supplementaryB) suppFiles.push('/workspace/supplementary-b.txt');
    if (suppFiles.length > 0) {
      finalPrompt += `\n\n# Additional Data Files\n${suppFiles.map((f) => `- ${f}`).join('\n')}`;
    }

    // 5. Setup Isolated Volume
    const tenantId = (context as any).tenantId ?? 'default-tenant';
    const volume = createIsolatedVolume(tenantId, context.runId);

    try {
      // 6. Build wrapper script
      // Claude Code uses `claude -p` for headless print mode
      // --dangerously-skip-permissions: required for non-interactive container usage
      // --output-format text: clean text output
      // --no-session-persistence: no state between runs in container
      // --mcp-config: path to MCP server config JSON
      // --model: specify which model to use (if set)
      const modelFlag = providerEnv.CLAUDE_CODE_MODEL
        ? `--model ${providerEnv.CLAUDE_CODE_MODEL}`
        : '';

      const wrapperScript = [
        '#!/bin/sh',
        'set -e',
        'cd /workspace',
        'claude -p \\',
        '  --dangerously-skip-permissions \\',
        '  --output-format text \\',
        '  --no-session-persistence \\',
        '  --mcp-config /workspace/mcp-config.json \\',
        ...(modelFlag ? [`  ${modelFlag} \\`] : []),
        '  "$(cat /workspace/prompt.txt)"',
        '',
      ].join('\n');

      // Remove the internal model env var — it was only used for script generation
      delete providerEnv.CLAUDE_CODE_MODEL;

      const mcpConfigJson = JSON.stringify(mcpConfig, null, 2);

      // Initialize workspace files
      const workspaceFiles: Record<string, string> = {
        'context.json': contextJson,
        'mcp-config.json': mcpConfigJson,
        'prompt.txt': finalPrompt,
        'run.sh': wrapperScript,
      };
      if (supplementaryA) workspaceFiles['supplementary-a.txt'] = supplementaryA;
      if (supplementaryB) workspaceFiles['supplementary-b.txt'] = supplementaryB;

      // Inject selected agent skills into workspace
      const skillFiles = await getSkillWorkspaceFiles(
        organizationId ?? null,
        selectedSkills,
        '.claude/skills',
      );
      const skillCount = Object.keys(skillFiles).length;
      if (skillCount > 0) {
        context.logger.info(
          `[ClaudeCode] Injecting ${skillCount} skill(s): ${Object.keys(skillFiles).join(', ')}`,
        );
      } else if (selectedSkills && selectedSkills.length > 0) {
        context.logger.warn(`[ClaudeCode] No skills found matching: ${selectedSkills.join(', ')}`);
      }
      Object.assign(workspaceFiles, skillFiles);

      await volume.initialize(workspaceFiles);

      const runnerConfig = {
        ...definition.runner,
        entrypoint: '/bin/sh',
        command: ['/workspace/run.sh'],
        network: 'host' as const,
        env: { ...providerEnv, HOME: '/tmp' },
        volumes: [
          volume.getVolumeConfig('/workspace', false), // Read-write
        ],
        workingDir: '/workspace',
        expectOutputFile: false,
      };

      context.emitProgress({
        message: 'Running Claude Code agent...',
        level: 'info',
      });

      const runnerResult = await runComponentWithRunner(
        runnerConfig,
        async (raw) => raw,
        {},
        context,
      );

      let stdout = '';
      let stderr = '';

      if (typeof runnerResult === 'string') {
        stdout = runnerResult;
      } else if (isRecord(runnerResult)) {
        stdout = (runnerResult.stdout as string) || (runnerResult.raw as string) || '';
        stderr = (runnerResult.stderr as string) || '';
      }

      return outputSchema.parse({
        report: cleanReport(stdout),
        rawOutput: `STDOUT:\n${stdout}\n\nSTDERR:\n${stderr}`,
      });
    } finally {
      await volume.cleanup();
    }
  },
});

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Clean report output from Claude Code.
 * Claude's `-p` (print) mode outputs clean text, so minimal cleanup is needed.
 */
function cleanReport(raw: string): string {
  return raw.trim();
}

/**
 * Build environment variables for Claude Code's Anthropic API auth.
 *
 * - LiteLLM routing: ANTHROPIC_API_KEY=<virtual-key>, ANTHROPIC_BASE_URL=<litellm>/anthropic
 * - Direct Anthropic: ANTHROPIC_API_KEY=<key>
 * - ZAI provider: ANTHROPIC_API_KEY=<key>, ANTHROPIC_BASE_URL=https://api.z.ai/api/coding/paas/v4
 */
function buildProviderEnv(
  model?: { provider: string; apiKey?: string },
  orgVirtualKey?: string,
): Record<string, string> {
  const liteLLMBaseUrl = process.env.LITELLM_BASE_URL?.trim();

  if (liteLLMBaseUrl) {
    const key = model?.apiKey || orgVirtualKey;
    return key
      ? {
          ANTHROPIC_API_KEY: key,
          ANTHROPIC_BASE_URL: liteLLMBaseUrl.replace(/\/v1\/?$/, '').replace(/\/+$/, ''),
        }
      : {};
  }

  if (!model?.apiKey) {
    return {};
  }

  switch (model.provider) {
    case 'anthropic':
      return { ANTHROPIC_API_KEY: model.apiKey };
    case 'zai-coding-plan':
      return {
        ANTHROPIC_API_KEY: model.apiKey,
        ANTHROPIC_BASE_URL: 'https://api.z.ai/api/anthropic',
      };
    default:
      // Claude Code natively uses Anthropic API; for other providers,
      // pass the key as ANTHROPIC_API_KEY and hope the base URL is set elsewhere
      return { ANTHROPIC_API_KEY: model.apiKey };
  }
}

componentRegistry.register(definition);
