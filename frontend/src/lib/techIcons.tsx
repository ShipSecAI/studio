/** Returns the matching Simple Icon component for a technology name, or null. */
export function getTechIcon(techName: string): ComponentType<IconBaseProps> | null {
  return TECH_ICON_MAP[techName.toLowerCase()] ?? null;
}

/** Returns the brand color hex for a technology name, or undefined. */
export function getTechColor(techName: string): string | undefined {
  return TECH_COLOR_MAP[techName.toLowerCase()];
}
